#!/usr/bin/env python3
"""Render .mergify.yml from the gatekeeper pack's deployed mergify.yml template.

Usage: render-mergify.py [--check]   (no flag rewrites .mergify.yml; --check exits 1 when it is stale)

The template's queue-only variant (its header says how) with this fork's values: base `mine`, the `gate`
merge condition, batch size and timeout sized to `gate.yml`, and a `sync` queue that merges `sync/*` heads
with a merge commit (`land.merge_commit_heads` in docs/agents/gatekeeper.md). Rerun after `apm install`
moves the pack.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TEMPLATE = ROOT / ".agents/plugins/gatekeeper/skills/gatekeeper/mergify.yml"
OUTPUT = ROOT / ".mergify.yml"

HEADER = """\
# yaml-language-server: $schema=https://docs.mergify.com/mergify-configuration-schema.json
#
# GENERATED by .claude/skills/cloud-dev/render-mergify.py from the gatekeeper pack's mergify.yml (read its header for
# what each key does); edit that script, never this file, and rerun it after the pack moves. This fork's changes to
# the template: base `mine`; the queue-only variant, so `merge_conditions` is `check-success = gate` (`gate` runs on
# Mergify's draft PRs alone, `.github/workflows/gate.yml`); `batch_size` 5; `checks_timeout` above `gate`'s
# 240-minute job timeout; the `default` queue leaves `sync/*` heads to the `sync` queue, which merges them with a
# merge commit so `mine` keeps upstream's parent (`land.merge_commit_heads`, docs/agents/gatekeeper.md); and
# `commands_restrictions` limits `@mergifyio queue` to write access.

"""

# (old, new, expected occurrences) applied to the template's body
EDITS = [
    ("base = main", "base = mine", 2),
    ("batch_size: 3", "batch_size: 5", 1),
    ("checks_timeout: 1 hour\n", "checks_timeout: 4 hours 15 minutes\n", 1),
    ("      - -conflict\n", "      - check-success = gate\n", 1),
    ("      - -draft\n", "      - -draft\n      - -head ~= ^sync/\n", 2),
]

SYNC_QUEUE = """\
  # An upstream-sync PR keeps upstream's parent (docs/agents/gatekeeper.md).
  - name: sync
    merge_method: merge
    batch_size: 1
    max_checks_retries: 1
    checks_timeout: 4 hours 15 minutes
    queue_conditions:
      - base = mine
      - -draft
      - head ~= ^sync/
      - label = loop:queued
      - -label = loop:hold
      - check-success = land
    merge_conditions:
      - check-success = gate

"""

SYNC_RULE = """\
  - name: queue a handed-over upstream sync
    conditions:
      - base = mine
      - -draft
      - head ~= ^sync/
      - label = loop:queued
      - -label = loop:hold
      - check-success = land
    actions:
      queue:
        name: sync

"""

RESTRICTIONS = """
commands_restrictions:
  queue:
    conditions:
      - sender-permission >= write
"""


def render() -> str:
    body = TEMPLATE.read_text()
    body = body[body.index("queue_rules:") :]
    for old, new, count in EDITS:
        if body.count(old) != count:
            sys.exit(f"render-mergify: the template changed: {old!r} appears {body.count(old)}x, not {count}x")
    for old, new, _ in EDITS:
        body = body.replace(old, new)
    for anchor, block in (("pull_request_rules:", SYNC_QUEUE), ("merge_queue:", SYNC_RULE)):
        if body.count(anchor) != 1:
            sys.exit(f"render-mergify: the template changed: no single {anchor!r}")
        body = body.replace(anchor, block + anchor)
    return HEADER + body.rstrip("\n") + "\n" + RESTRICTIONS


if __name__ == "__main__":
    rendered = render()
    if "--check" in sys.argv:
        if OUTPUT.read_text() != rendered:
            sys.exit(".mergify.yml is stale: run .claude/skills/cloud-dev/render-mergify.py")
    else:
        OUTPUT.write_text(rendered)
